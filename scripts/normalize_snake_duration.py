#!/usr/bin/env python3
"""Raise only an unusually short snk SVG animation duration.

The contribution cells, keyframes, positions, colors, and path are preserved.
This helper changes the single shared CSS animation duration generated by
Platane/snk only when it is below the configured minimum.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path


STYLE_PATTERN = re.compile(r"(<style>)(.*?)(</style>)", re.DOTALL)
DURATION_PATTERN = re.compile(r"(?<![\w.-])(\d+)ms(?![\w.-])")


def normalize_svg_text(svg: str, minimum_ms: int) -> tuple[str, int, int, bool]:
    """Return normalized SVG and original/effective duration metadata."""
    style_match = STYLE_PATTERN.search(svg)
    if style_match is None:
        raise ValueError("SVG does not contain a <style> block")

    style = style_match.group(2)
    durations = sorted({int(value) for value in DURATION_PATTERN.findall(style)})
    if not durations:
        raise ValueError("SVG style does not contain a millisecond duration")
    if len(durations) != 1:
        raise ValueError(f"expected one shared duration, found: {durations}")

    original_ms = durations[0]
    effective_ms = max(original_ms, minimum_ms)
    if effective_ms == original_ms:
        return svg, original_ms, effective_ms, False

    normalized_style = DURATION_PATTERN.sub(f"{effective_ms}ms", style)
    normalized_svg = (
        svg[: style_match.start(2)]
        + normalized_style
        + svg[style_match.end(2) :]
    )
    return normalized_svg, original_ms, effective_ms, True


def normalize_file(path: Path, minimum_ms: int) -> None:
    source = path.read_text(encoding="utf-8")
    normalized, original_ms, effective_ms, changed = normalize_svg_text(
        source, minimum_ms
    )

    if changed:
        temporary = path.with_suffix(path.suffix + ".tmp")
        temporary.write_text(normalized, encoding="utf-8")
        temporary.replace(path)

    cell_count = len(re.findall(r'class="c(?:\s|\")', normalized))
    snake_part_count = len(re.findall(r'class="s s\d+"', normalized))
    status = "normalized" if changed else "unchanged"
    print(
        f"{path}: {status}; duration={original_ms}ms->{effective_ms}ms; "
        f"cells={cell_count}; snake_parts={snake_part_count}"
    )


def run_self_test() -> None:
    short_svg = (
        '<svg><desc>100ms outside style</desc><style>'
        '.c{animation:none 100ms linear infinite}'
        '.s{animation:none linear 100ms infinite}'
        '</style><rect class="s s0"/></svg>'
    )
    normalized, original, effective, changed = normalize_svg_text(short_svg, 12000)
    assert changed is True
    assert original == 100
    assert effective == 12000
    assert normalized.count("12000ms") == 2
    assert "100ms outside style" in normalized

    normal_svg = '<svg><style>.s{animation:none linear 15000ms infinite}</style></svg>'
    untouched, original, effective, changed = normalize_svg_text(normal_svg, 12000)
    assert changed is False
    assert original == effective == 15000
    assert untouched == normal_svg

    inconsistent_svg = (
        '<svg><style>.c{animation:none 100ms linear infinite}'
        '.s{animation:none 200ms linear infinite}</style></svg>'
    )
    try:
        normalize_svg_text(inconsistent_svg, 12000)
    except ValueError as error:
        assert "expected one shared duration" in str(error)
    else:
        raise AssertionError("inconsistent durations must fail closed")

    print("self-test: ok")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("files", nargs="*", type=Path)
    parser.add_argument("--minimum-ms", type=int, default=12000)
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    if args.minimum_ms <= 0:
        parser.error("--minimum-ms must be greater than zero")
    if not args.self_test and not args.files:
        parser.error("provide at least one SVG file or use --self-test")
    return args


def main() -> int:
    args = parse_args()
    try:
        if args.self_test:
            run_self_test()
        for path in args.files:
            normalize_file(path, args.minimum_ms)
    except (OSError, ValueError, AssertionError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
